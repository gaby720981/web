//permite multiples cambios a partir de la evaluacion de una sola expresion/condicion

var color = 'rojo';

switch (color) {    
    case 'rojo':
        console.log('El color es rojo');
        break;      
    case 'azul':
        console.log('El color es azul');
        break;
    case 'verde':
        console.log('El color es verde');
        break;  
    default:
        console.log('El color es desconocido');
        break;
    }   
