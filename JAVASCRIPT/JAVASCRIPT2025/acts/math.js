

// Uso de Math.round() para redondear un número decimal
let numeroDecimal = 4.56;
let redondeado = Math.round(numeroDecimal);
console.log("Número redondeado:", redondeado); // Resultado: 5

// Uso de Math.pow() para elevar un número a una potencia
let base = 2;
let exponente = 3;
let potencia = Math.pow(base, exponente);
console.log("Potencia:", potencia); // Resultado: 8

// Uso de Math.sqrt() para obtener la raíz cuadrada
let numeroRaiz = 16;
let raiz = Math.sqrt(numeroRaiz);
console.log("Raíz cuadrada:", raiz); // Resultado: 4

// Uso de Math.random() para generar un número aleatorio entre 0 y 1
let numeroAleatorio = Math.random();
console.log("Número aleatorio entre 0 y 1:", numeroAleatorio);

// Uso de Math.max() y Math.min() para encontrar el valor máximo y mínimo en un conjunto de números
let numeros = [5, 12, 8, 22, 3];
let maximo = Math.max(...numeros);
let minimo = Math.min(...numeros);
console.log("Máximo:", maximo); // Resultado: 22
console.log("Mínimo:", minimo); // Resultado: 3

// Uso de Math.abs() para obtener el valor absoluto de un número
let numeroNegativo = -15;
console.log("Valor absoluto:", Math.abs(numeroNegativo));  // Resultado: 15

